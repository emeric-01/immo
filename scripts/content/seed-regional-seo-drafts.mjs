async function upsertDraft(article, config) {
  const existing = await request(
    `/rest/v1/content_articles?select=id,status&slug=eq.${encodeURIComponent(article.slug)}&limit=1`,
    config,
  );

  if (existing[0]?.status === "published") {
    throw new Error(`Refus d’écraser l’article publié ${article.slug}.`);
  }

  const now = new Date().toISOString();
  const payload = {
    body_markdown: article.body.trim(),
    category: article.category,
    cover_image_alt: null,
    cover_image_url: null,
    excerpt: article.excerpt,
    primary_keyword: article.primaryKeyword,
    published_at: null,
    reading_minutes: Math.max(1, Math.ceil(countWords(article.body) / 220)),
    related_city_slug: article.relatedCitySlug,
    seo_description: article.seoDescription,
    seo_title: article.seoTitle,
    slug: article.slug,
    status: "draft",
    title: article.title,
    updated_at: now,
    updated_by_admin_id: null,
  };

  if (existing[0]) {
    await request(`/rest/v1/content_articles?id=eq.${existing[0].id}`, config, {
      body: JSON.stringify(payload),
      headers: { Prefer: "return=minimal" },
      method: "PATCH",
    });
    console.log(`updated ${article.slug}`);
    return;
  }

  await request("/rest/v1/content_articles", config, {
    body: JSON.stringify({ ...payload, created_at: now, created_by_admin_id: null }),
    headers: { Prefer: "return=minimal" },
    method: "POST",
  });
  console.log(`created ${article.slug}`);
}

async function request(path, config, init = {}) {
  const response = await fetch(`${config.supabaseUrl}${path}`, {
    ...init,
    headers: { ...config.headers, ...init.headers },
  });

  if (!response.ok) {
    throw new Error(`${response.status} ${await response.text()}`);
  }

  return response.status === 204 ? null : response.json();
}

function countWords(value) {
  return value
    .replace(/https?:\/\/\S+/g, " ")
    .replace(/[#>*_`\[\]().|:-]/g, " ")
    .split(/\s+/)
    .filter(Boolean)
    .length;
}
